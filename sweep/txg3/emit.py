# Writes Solution/TxDefs.lean, Solution/TxChunk*.lean and Solution/TxTop.lean from sweep/txg3/cert.json.
import json, sys
sys.set_int_max_str_digits(0)
J = json.load(open('sweep/txg3/cert.json'))
cm, cn = J['cm'], J['cn']
N = 48
def enc(es):
    v = 0
    for e in reversed(es):
        v = v * 64 + e
    return v

def tree(lo, hi, leaf):
    if hi - lo == 1: return leaf(lo)
    mid = (lo + hi) // 2
    return f"(bif Nat.blt u {mid} then {tree(lo, mid, leaf)} else {tree(mid, hi, leaf)})"

tb = tree(0, N, lambda u: '[' + ', '.join(f'({w}, {cm[w]})' for w in cn[u]) + ']')
defs = f'''/-! Definitions for the txgraffiti3 certificate: the graph table and the certificate checker.
The graph is the connected cubic graph on 48 vertices from
https://github.com/ipitchford/txgraffiti-order48-successor (file `counterexample.edgelist`).
Generated by `sweep/txg3/emit.py`. -/

noncomputable section

namespace Tx

/-- Closed-neighbourhood masks: bit `v` of `cmL[u]` is set iff `v = u` or `uv` is an edge. -/
def cmL : List Nat := {cm}

def cmT (u : Nat) : Nat := cmL.getD u 0

/-- For a vertex `u`, the list of `(w, cmT w)` for `w` in the closed neighbourhood of `u`
(first `u`, then its neighbours in increasing order). Binary search on `u` for kernel speed. -/
def tb (u : Nat) : List (Nat × Nat) :=
  {tb}

/-- Bit `v` of `d`, with raw `Nat` operations for kernel speed. -/
def bit (d v : Nat) : Bool := Nat.beq (Nat.land (Nat.shiftRight d v) 1) 1

/-- Number of `v < 48` whose bit in `d` is clear. -/
def cnt (d : Nat) : Nat :=
  Nat.rec (motive := fun _ => Nat) 0
    (fun i r => Nat.add r (Nat.sub 1 (Nat.land (Nat.shiftRight d i) 1))) 48

/-- Is `(k, d, x)` in the list of already verified states? -/
def inOk (k d x : Nat) : List (Nat × Nat × Nat) → Bool
  | [] => false
  | s :: l => (Nat.beq s.1 k && Nat.beq s.2.1 d && Nat.beq s.2.2 x) || inOk k d x l

/-- Children of a branch node: for each `(w, m)` in the list, skip `w` if it is dominated (`d`)
or excluded (`x`); otherwise check the child state `(d ∪ m, x)` with `f` and then exclude `w`. -/
def brL (f : Nat → Nat → Nat → Option Nat) (d : Nat) (L : List (Nat × Nat)) : Nat → Nat → Option Nat :=
  List.rec (motive := fun _ => Nat → Nat → Option Nat) (fun _ c => some c)
    (fun p _ r x c => bif bit d p.1 || bit x p.1 then r x c else
      Option.rec none (fun c' => r (Nat.lor x (Nat.pow 2 p.1)) c') (f (Nat.lor d p.2) x c)) L

/-- One node of the certificate with budget `k`. The next 6 bits `e` of `c` say:
`48` = bound leaf (more than `4k` undominated vertices), `49` = verified state in `ok`,
`u < 48` = branch on the undominated vertex `u` (handled by `br`). -/
def nd (ok : List (Nat × Nat × Nat)) (k d x c : Nat) (br : Nat → Nat → Option Nat) : Option Nat :=
  bif Nat.beq (Nat.land c 63) 48 then
    (bif Nat.blt (Nat.mul 4 k) (cnt d) then some (Nat.shiftRight c 6) else none)
  else bif Nat.beq (Nat.land c 63) 49 then
    (bif inOk k d x ok then some (Nat.shiftRight c 6) else none)
  else br (Nat.land c 63) (Nat.shiftRight c 6)

/-- The checker: `chk ok k d x c` reads one subtree from `c` and returns the rest of `c`. -/
def chk (ok : List (Nat × Nat × Nat)) (k : Nat) : Nat → Nat → Nat → Option Nat :=
  Nat.rec (motive := fun _ => Nat → Nat → Nat → Option Nat)
    (fun d x c => nd ok 0 d x c (fun _ _ => none))
    (fun k f d x c => nd ok (k + 1) d x c (fun e c' =>
      bif Nat.blt e 48 && !(bit d e) then brL f d (tb e) x c' else none)) k

end Tx

end
'''
open('Solution/TxDefs.lean', 'w').write(defs)

chunks = J['chunks']
# group chunks into modules of about MOD nodes
MOD = int(sys.argv[1]) if len(sys.argv) > 1 else 12000
mods = []; cur = []; size = 0
for i, (k, d, x, es) in enumerate(chunks):
    if cur and size + len(es) > MOD:
        mods.append(cur); cur = []; size = 0
    cur.append(i); size += len(es)
if cur: mods.append(cur)
for m, idxs in enumerate(mods):
    body = []
    for i in idxs:
        k, d, x, es = chunks[i]
        body.append(f'''/-- Chunk {i}: {len(es)} nodes. -/
theorem chunk{i} : (chk [] {k} {d} {x} {enc(es)}).isSome = true := by decide +kernel
''')
    open(f'Solution/TxChunk{m}.lean', 'w').write(f'''import Solution.TxDefs

/-! Kernel checks of certificate chunks for txgraffiti3 (generated by `sweep/txg3/emit.py`). -/

namespace Tx

''' + '\n'.join(body) + '\nend Tx\n')
print('modules', len(mods), [sum(len(chunks[i][3]) for i in ms) for ms in mods])
json.dump(mods, open('sweep/txg3/mods.json', 'w'))

# top-level module
top = J['top']
oks = ',\n  '.join(f'({k}, {d}, {x})' for (k, d, x, es) in chunks)
imports = '\n'.join(f'import Solution.TxChunk{m}' for m in range(len(mods)))
names = ',\n    '.join(f'chk_sound\' chunk{i}' for i in range(len(chunks)))
open('Solution/TxTop.lean', 'w').write(f'''import Solution.TxSound
{imports}

/-! The top of the certificate tree for txgraffiti3; its frontier states are the chunk roots
(generated by `sweep/txg3/emit.py`). -/

namespace Tx

/-- Root states of the chunks, as `(k, d, x)`. -/
def okList : List (Nat × Nat × Nat) := [
  {oks}]

theorem okList_P : ∀ s ∈ okList, P s.1 s.2.1 s.2.2 := by
  simp only [okList, List.forall_mem_cons]
  exact ⟨
    {names},
    fun _ h => by cases h⟩

theorem top_run : (chk okList 15 0 0 {enc(top)}).isSome = true := by decide +kernel

/-- No independent dominating set with at most 15 vertices. -/
theorem P15 : P 15 0 0 := by
  obtain ⟨r, hr⟩ := Option.isSome_iff_exists.mp top_run
  exact chk_sound okList okList_P 15 0 0 _ r hr

end Tx
''')
