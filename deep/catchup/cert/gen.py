#!/usr/bin/env python3
"""Generate minimal Catch-Up draw certificates (gap form) for {1..N} and emit Lean.

usage: gen.py N outfile
"""
import sys
from functools import lru_cache
sys.setrecursionlimit(100000)

WIN, LOSS, DRAW = 2, 0, 1  # order loss < draw < win

def main():
    N = int(sys.argv[1]); out = sys.argv[2]
    full = (1 << N) - 1
    elems = lambda m: [i + 1 for i in range(N) if m >> i & 1]
    msum = {}
    for m in range(1 << N):
        msum[m] = sum(elems(m))

    @lru_cache(maxsize=None)
    def gv(m, g):
        if m == 0:
            return DRAW if g == 0 else LOSS
        if msum[m] < g:
            return LOSS
        best = LOSS
        for x in elems(m):
            m2 = m & ~(1 << (x - 1))
            if g <= x:
                o = 2 - gv(m2, x - g)
            else:
                o = gv(m2, g - x)
            if o > best:
                best = o
                if best == WIN:
                    break
        return best

    # minimal certificates; size = number of Cert nodes
    @lru_cache(maxsize=None)
    def ge(m, g):  # requires gv(m,g) != LOSS; returns (size, cert)
        if m == 0:
            assert g == 0
            return (1, ('leaf',))
        best = None
        for x in elems(m):
            m2 = m & ~(1 << (x - 1))
            if g <= x:
                if gv(m2, x - g) == WIN:
                    continue
                s, c = le(m2, x - g)
            else:
                if gv(m2, g - x) == LOSS:
                    continue
                s, c = ge(m2, g - x)
            if best is None or s + 1 < best[0]:
                best = (s + 1, ('pick', x, c))
        assert best is not None
        return best

    @lru_cache(maxsize=None)
    def le(m, g):  # requires gv(m,g) != WIN
        if m == 0 or msum[m] < g:
            return (1, ('leaf',))
        tot = 1; subs = []
        for x in elems(m):
            m2 = m & ~(1 << (x - 1))
            if g <= x:
                assert gv(m2, x - g) != LOSS
                s, c = ge(m2, x - g)
            else:
                assert gv(m2, g - x) != WIN
                s, c = le(m2, g - x)
            tot += s; subs.append((x, c))
        return (tot, ('all', subs))

    v = gv(full, 0)
    print('N', N, 'value', v)
    assert v == DRAW
    sge, cge = ge(full, 0)
    sle, cle = le(full, 0)
    print('sizes ge', sge, 'le', sle)

    # independent literal checker on lists
    def keys(subs):
        return [x for x, _ in subs]
    def erase(l, x):
        l = list(l); l.remove(x); return l
    def chkGe(l, g, c):
        if c[0] == 'leaf':
            return len(l) == 0 and g == 0
        if c[0] == 'pick':
            x, sub = c[1], c[2]
            if not (x in l and not (sum(l) < g)):
                return False
            return chkLe(erase(l, x), x - g, sub) if g <= x else chkGe(erase(l, x), g - x, sub)
        return False
    def chkLe(l, g, c):
        if c[0] == 'leaf':
            return len(l) == 0 or sum(l) < g
        if c[0] == 'all':
            ks = keys(c[1])
            if not all(x in ks for x in l):
                return False
            for x, sub in c[1]:
                if x not in l:
                    return False
                ok = chkGe(erase(l, x), x - g, sub) if g <= x else chkLe(erase(l, x), g - x, sub)
                if not ok:
                    return False
            return True
        return False
    L = list(range(1, N + 1))
    assert chkGe(L, 0, cge), 'ge check failed'
    assert chkLe(L, 0, cle), 'le check failed'
    print('python check ok')

    def emit(c):
        parts = []
        def go(c):
            if c[0] == 'leaf':
                parts.append('Cert.leaf')
            elif c[0] == 'pick':
                parts.append('(Cert.pick %d ' % c[1]); go(c[2]); parts.append(')')
            else:
                parts.append('(Cert.all ')
                for x, sub in c[1]:
                    parts.append('(CertList.cons %d ' % x); go(sub); parts.append(' ')
                parts.append('CertList.nil' + ')' * len(c[1]) + ')')
        go(c)
        return ''.join(parts)

    with open(out, 'w') as f:
        f.write('import Solution.Cert\n\n')
        f.write('/-! Minimal strategy certificates for the Catch-Up game on {1, ..., %d}\n' % N)
        f.write('(generated by `deep/catchup/cert/gen.py`; %d ge-nodes, %d le-nodes). -/\n\n' % (sge, sle))
        f.write('namespace CatchUpDeep\n\nopen CatchUp\n\n')
        f.write('set_option maxRecDepth 100000 in\n')
        f.write('/-- certificate that the first player secures at least a draw on {1..%d} -/\n' % N)
        f.write('def cert%dge : Cert :=\n  %s\n\n' % (N, emit(cge)))
        f.write('set_option maxRecDepth 100000 in\n')
        f.write('/-- certificate that the first player gets at most a draw on {1..%d} -/\n' % N)
        f.write('def cert%dle : Cert :=\n  %s\n\n' % (N, emit(cle)))
        f.write('set_option maxRecDepth 100000 in\n')
        f.write('theorem catchup_draw_%d : value (Finset.Icc 1 %d) = .draw :=\n' % (N, N))
        f.write('  value_Icc_eq_draw_of_certs %d cert%dge cert%dle (by decide +kernel) (by decide +kernel)\n\n' % (N, N, N))
        f.write('end CatchUpDeep\n\n#print axioms CatchUpDeep.catchup_draw_%d\n' % N)
    print('wrote', out)

main()
